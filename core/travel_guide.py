def identify_dynasty(year):
    """根据年份识别朝代"""
    eras = [
        (-2070, -1600, "夏"), (-1600, -1046, "商"),
        (-1046, -771, "西周"), (-771, -256, "东周/春秋战国"),
        (-221, -207, "秦"), (-202, 8, "西汉"),
        (25, 220, "东汉"), (220, 280, "三国"),
        (265, 316, "西晋"), (317, 420, "东晋"),
        (420, 589, "南北朝"), (581, 618, "隋"),
        (618, 907, "唐"), (907, 960, "五代十国"),
        (960, 1279, "宋"), (1271, 1368, "元"),
        (1368, 1644, "明"), (1644, 1912, "清"),
        (1912, 1949, "民国"),
    ]
    for start, end, dynasty in eras:
        if start <= year <= end:
            return dynasty
    return "未知"


def get_survival_guide(year, location=""):
    """生成穿越生存指南"""
    dynasty = identify_dynasty(year)
    info = DYNASTY_INFO.get(dynasty, {})

    # 获取同期知名人物
    chars = load_characters()
    contemporaries = [c for c in chars if (c["birth_year"] or 0) <= year <= (c["death_year"] or 9999)]

    # 获取同期大事件
    events = load_events()
    nearby_events = [e for e in events if abs(e["year"] - year) <= 5]

    # 尝试用 LLM 生成更生动的版本
    prompt = f"""用户想穿越到{year}年{dynasty}时期的{location if location else '中国'}。
请用200字左右给出一份实用的穿越生存指南，包括：
1. 那里是什么情况
2. 需要注意什么
3. 有什么有趣的事

语气要有趣又实用，像有经验的人在传授秘诀。"""

    if llm_result := chat("你是一个穿越生存专家，熟悉中国各朝代历史。注意：对用户使用中性称呼，不要用兄弟、老铁等口语化称呼。", prompt):
        guide = f"## {year}年 / {dynasty}"
        if location:
            guide += f" · {location}"
        guide += f"\n\n**🔮 年代概况**\n{llm_result}\n"
        if info:
            guide += f"\n\n---\n### 📋 穿越者实用参考\n"
            guide += f"- **👑 都城**：{info.get('capital', '未知')}\n"
            guide += f"- **💬 语言**：{info.get('language', '未知')}\n"
            guide += f"- **💰 货币**：{info.get('currency', '未知')}\n"
            guide += f"- **👘 服饰**：{info.get('dress', '未知')}\n"
            guide += f"- **🍜 饮食**：{info.get('food', '未知')}\n"
            guide += f"- **🏠 住宿**：{info.get('stay', '未知')}\n"
            guide += f"- **⚠️ 禁忌**：{'；'.join(info.get('taboo', []))}\n"
            guide += f"- **☠️ 危险**：{info.get('danger', '未知')}\n"
        for pn, pd, ps, pe, pnote in PERIOD_NOTES:
            if pd == dynasty and ps <= year <= pe:
                guide += f"\n**📌 时期提示（{pn}）**：{pnote}\n"
                break
        if contemporaries:
            guide += f"\n**👤 你可能遇到的知名人物**：{'、'.join([c['name'] for c in contemporaries[:5]])}\n"
        if nearby_events:
            guide += f"\n**📜 同期大事**：{'、'.join([e['name'] for e in nearby_events[:3]])}\n"
        return guide

    # 模拟模式
    if not info:
        return f"## {year}年 {dynasty if dynasty else ''} {location}\n\n抱歉，这个时期的数据还不够完整。你到了一个史书上记载不多年代！"

    guide = f"## {year}年 / {dynasty}"
    if location:
        guide += f" · {location}"
    guide += f"\n\n"
    guide += f"你穿越到了{dynasty}时期的{location if location else '中国'}。这里充满{'了机遇与危险' if year < 1800 else '了变革与动荡'}。\n\n---\n\n"
    for pn, pd, ps, pe, pnote in PERIOD_NOTES:
        if pd == dynasty and ps <= year <= pe:
            guide += f"**📌 时期提示（{pn}）**：{pnote}\n\n"
            break
    guide += f"### 📋 穿越者实用参考\n\n"
