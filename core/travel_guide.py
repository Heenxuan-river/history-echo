    guide += f"- **🍜 饮食**：{info['food']}\n"
    guide += f"- **🏠 住宿**：{info['stay']}\n"
    guide += f"- **⚠️ 禁忌**：{'；'.join(info['taboo'])}\n"
    guide += f"- **☠️ 危险**：{info['danger']}\n"
    if contemporaries:
        guide += f"\n### 👤 你可能遇到的知名人物\n{'、'.join([c['name'] for c in contemporaries[:5]])}\n"
    if nearby_events:
        guide += f"\n### 📜 这个时期的大事\n{'、'.join([e['name'] for e in nearby_events[:3]])}\n"

