# ── 通用人物兜底回复 ──
def get_fallback(char):
    desc = char.get("description", "")[:50]
    name = char["name"]
    dynasty = char.get("dynasty", "")
    quotes = char.get("quotes", [])
    achievements = char.get("achievements", [])
    personality = char.get("personality", [])

    replies = [
        f"你这个问题让我想起了我生活的那个时代。在{dynasty}，情况是这样的……",
        f"以我的经历来看，{desc}。所以我的看法是……",
        f"哈哈，你提到了一个很有意思的点。我们{dynasty}的人可不是这么想的。",
        f"作为一个{name}，我{'、'.join(personality[:2])}。在我看来……",
    ]
    if achievements:
        replies.append(f"我这一生最大的成就莫过于{'、'.join(achievements[:2])}。")
    if quotes:
        replies.append(f"这让我想起了一句我说过的话：「{random.choice(quotes)}」")

    return random.choice(replies)


def generate_reply(char_id, user_message, history=None):
    character = get_character_by_id(char_id)
    if not character:
        return "找不到这个人物。"

    # 有 API Key 时走 LLM
    if llm_result := chat(
        f"你是{character['name']}，{character['description']}。"
        f"性格：{'、'.join(character.get('personality', []))}。"
        f"请完全代入角色，用自己的口吻回答，控制在150字以内。注意：对用户使用中性称呼，不要用兄弟、老铁、哥们等口语化称呼。",
        user_message,
    ):
        return llm_result

    # 模拟模式：查人物专属回复表
    char_replies = PERSONALITY_REPLIES.get(char_id, {})
    for pattern, replies in char_replies.items():
        if re.search(pattern, user_message):
            return random.choice(replies)

    # 兜底
    return get_fallback(character)


